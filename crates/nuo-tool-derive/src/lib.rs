//! Procedural macros for the Nuo tool system.
//!
//! Provides `#[derive(ToolArgs)]` and its backward-compatible alias `#[derive(ToolSchema)]`.
//! Inspects Rust structs or unit enums at compile time to generate draft-07 JSON Schema
//! specifications (`parameters_schema() -> serde_json::Value` and `raw_schema() -> &'static str`).
//!
//! # Supported Features
//!
//! - **Doc-comments First**: Automatically extracts `/// ...` doc-comments into the schema's
//!   `description`.
//! - **Explicit Descriptions & Aliases**: Supports `#[tool(desc = "...")]` and
//!   `#[tool(description = "...")]` to override or provide descriptions.
//! - **Serde Interoperability**: Respects `#[serde(rename = "...")]`, `#[serde(skip)]`,
//!   `#[serde(skip_deserializing)]`, and container-level `#[serde(rename_all = "...")]`.
//! - **Choice/Enum Constrained Fields**: Supports `#[tool(choices = ["a", "b"])]` or
//!   `#[tool(enum = ["a", "b"])]` on string fields or arrays of strings.
//! - **Unit Enums**: Directly derives string-based enum schemas for field-less enums.
//! - **Zero-Allocation Const Embedding**: Emits a `const RAW_SCHEMA: &'static str` for
//!   instant zero-allocation schema string access alongside parsed `parameters_schema()`.
//! - **First-Class Trait Contract**: Implements `::nuo_tool::ToolArgs` while retaining
//!   inherent methods for complete backward compatibility.

#![cfg_attr(test, allow(clippy::unwrap_used, clippy::expect_used, clippy::panic))]

use proc_macro::TokenStream;
use quote::quote;
use syn::{Data, DeriveInput, Fields, Type, parse_macro_input};

/// Primary derive macro generating draft-07 JSON Schema and implementing `ToolArgs`.
#[proc_macro_derive(ToolArgs, attributes(tool))]
pub fn tool_args_derive(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand(input)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// Backward-compatible alias for [`tool_args_derive`].
#[proc_macro_derive(ToolSchema, attributes(tool))]
pub fn tool_schema_derive(input: TokenStream) -> TokenStream {
    let input = parse_macro_input!(input as DeriveInput);
    expand(input)
        .unwrap_or_else(syn::Error::into_compile_error)
        .into()
}

/// The expansion logic, split out so tests can drive it with `proc_macro2` token streams.
fn expand(input: DeriveInput) -> syn::Result<proc_macro2::TokenStream> {
    let name = &input.ident;
    let schema = build_schema(&input)?;
    let schema_str = serde_json::to_string(&schema)
        .map_err(|e| syn::Error::new_spanned(&input, format!("failed to serialize schema: {e}")))?;

    let (impl_generics, ty_generics, where_clause) = input.generics.split_for_impl();

    Ok(quote! {
        impl #impl_generics #name #ty_generics #where_clause {
            /// The draft-07 JSON Schema as a static compile-time string literal.
            pub const RAW_SCHEMA: &'static str = #schema_str;

            /// The draft-07 JSON Schema for this type, in the shape a tool advertises
            /// to the model (`{type: object, properties, required}`).
            /// Generated by `#[derive(ToolArgs)]` / `#[derive(ToolSchema)]`.
            pub fn parameters_schema() -> ::serde_json::Value {
                ::serde_json::from_str(Self::RAW_SCHEMA).expect("valid compile-time schema JSON")
            }

            /// The draft-07 JSON Schema as a zero-allocation static string slice.
            pub fn raw_schema() -> &'static str {
                Self::RAW_SCHEMA
            }
        }

        impl #impl_generics ::nuo_tool::ToolArgs for #name #ty_generics #where_clause {
            fn parameters_schema() -> ::serde_json::Value {
                Self::parameters_schema()
            }

            fn raw_schema() -> &'static str {
                Self::raw_schema()
            }
        }
    })
}

/// Build the draft-07 schema for the deriving struct or enum.
fn build_schema(input: &DeriveInput) -> syn::Result<serde_json::Value> {
    match &input.data {
        Data::Struct(data) => build_struct_schema(input, data),
        Data::Enum(data) => build_enum_schema(input, data),
        Data::Union(_) => Err(syn::Error::new_spanned(
            input,
            "ToolArgs / ToolSchema does not support unions",
        )),
    }
}

/// Build the schema for a struct with named fields.
fn build_struct_schema(
    input: &DeriveInput,
    data: &syn::DataStruct,
) -> syn::Result<serde_json::Value> {
    let fields = match &data.fields {
        Fields::Named(named) => &named.named,
        _ => {
            return Err(syn::Error::new_spanned(
                input,
                "ToolArgs / ToolSchema only supports structs with named fields",
            ));
        }
    };

    let mut properties = serde_json::Map::new();
    let mut required: Vec<serde_json::Value> = Vec::new();

    for field in fields {
        let meta = parse_field_meta(field)?;
        if meta.skip {
            continue;
        }

        let ident = field
            .ident
            .as_ref()
            .ok_or_else(|| syn::Error::new_spanned(field, "named fields required"))?;

        // 1. Determine property name (honoring #[serde(rename = "...")])
        let prop_name = meta.rename.unwrap_or_else(|| ident.to_string());

        // 2. Extract description: explicit #[tool(desc)] takes precedence over doc-comments
        let doc_desc = extract_doc_comment(&field.attrs);
        let final_desc = meta.description.or(doc_desc);

        // 3. Determine JSON type and optionality
        let (mut prop, optional) = json_type(&field.ty, meta.choices.as_deref());

        if let Some(desc) = final_desc {
            prop["description"] = desc.into();
        }

        if !optional {
            required.push(prop_name.clone().into());
        }

        properties.insert(prop_name, prop);
    }

    let mut schema = serde_json::json!({
        "type": "object",
        "properties": properties,
        "required": required,
        "additionalProperties": false,
    });

    if let Some(top_desc) = extract_doc_comment(&input.attrs) {
        schema["description"] = top_desc.into();
    }

    Ok(schema)
}

/// Build the schema for a field-less (unit) enum.
fn build_enum_schema(input: &DeriveInput, data: &syn::DataEnum) -> syn::Result<serde_json::Value> {
    let rename_all_rule = container_serde_rename_all(&input.attrs)?;
    let mut enum_values = Vec::new();

    for variant in &data.variants {
        if !matches!(variant.fields, Fields::Unit) {
            return Err(syn::Error::new_spanned(
                variant,
                "ToolArgs / ToolSchema only supports unit enums without fields",
            ));
        }

        let meta = parse_variant_meta(variant)?;
        if meta.skip {
            continue;
        }

        let val_name = if let Some(rename) = meta.rename {
            rename
        } else {
            let ident_str = variant.ident.to_string();
            if let Some(ref rule) = rename_all_rule {
                apply_rename_all(&ident_str, rule)
            } else {
                ident_str
            }
        };

        enum_values.push(serde_json::Value::String(val_name));
    }

    let mut schema = serde_json::json!({
        "type": "string",
        "enum": enum_values,
    });

    if let Some(top_desc) = extract_doc_comment(&input.attrs) {
        schema["description"] = top_desc.into();
    }

    Ok(schema)
}

struct ParsedFieldMeta {
    rename: Option<String>,
    description: Option<String>,
    choices: Option<Vec<String>>,
    skip: bool,
}

/// Parse attributes on a struct field (serde and tool attributes).
fn parse_field_meta(field: &syn::Field) -> syn::Result<ParsedFieldMeta> {
    let mut rename = None;
    let mut description = None;
    let mut choices = None;
    let mut skip = false;

    for attr in &field.attrs {
        if attr.path().is_ident("serde") {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("rename") {
                    let lit: syn::LitStr = meta.value()?.parse()?;
                    rename = Some(lit.value());
                } else if meta.path.is_ident("skip") || meta.path.is_ident("skip_deserializing") {
                    skip = true;
                } else if meta.input.peek(syn::Token![=]) {
                    let _: syn::Expr = meta.value()?.parse()?;
                }
                Ok(())
            })?;
        } else if attr.path().is_ident("tool") {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("desc") || meta.path.is_ident("description") {
                    let lit: syn::LitStr = meta.value()?.parse()?;
                    description = Some(lit.value());
                    Ok(())
                } else if meta.path.is_ident("choices") || meta.path.is_ident("enum") {
                    let expr: syn::ExprArray = meta.value()?.parse()?;
                    let mut list = Vec::new();
                    for elem in expr.elems {
                        if let syn::Expr::Lit(syn::ExprLit {
                            lit: syn::Lit::Str(s),
                            ..
                        }) = elem
                        {
                            list.push(s.value());
                        } else {
                            return Err(syn::Error::new_spanned(
                                elem,
                                "expected string literal in choices array",
                            ));
                        }
                    }
                    choices = Some(list);
                    Ok(())
                } else if meta.path.is_ident("skip") {
                    skip = true;
                    Ok(())
                } else {
                    Err(meta.error(
                        "unsupported `tool` attribute; expected `desc`, `description`, `choices`, or `skip`",
                    ))
                }
            })?;
        }
    }

    Ok(ParsedFieldMeta {
        rename,
        description,
        choices,
        skip,
    })
}

struct ParsedVariantMeta {
    rename: Option<String>,
    skip: bool,
}

fn parse_variant_meta(variant: &syn::Variant) -> syn::Result<ParsedVariantMeta> {
    let mut rename = None;
    let mut skip = false;

    for attr in &variant.attrs {
        if attr.path().is_ident("serde") {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("rename") {
                    let lit: syn::LitStr = meta.value()?.parse()?;
                    rename = Some(lit.value());
                } else if meta.path.is_ident("skip") || meta.path.is_ident("skip_deserializing") {
                    skip = true;
                } else if meta.input.peek(syn::Token![=]) {
                    let _: syn::Expr = meta.value()?.parse()?;
                }
                Ok(())
            })?;
        } else if attr.path().is_ident("tool") {
            attr.parse_nested_meta(|meta| {
                if meta.path.is_ident("desc") || meta.path.is_ident("description") {
                    let lit: syn::LitStr = meta.value()?.parse()?;
                    let _ = lit;
                    Ok(())
                } else if meta.path.is_ident("skip") {
                    skip = true;
                    Ok(())
                } else {
                    Err(meta.error(
                        "unsupported `tool` attribute on variant; expected `desc`, `description`, or `skip`",
                    ))
                }
            })?;
        }
    }

    Ok(ParsedVariantMeta { rename, skip })
}

/// Extract doc-comments from attributes (`#[doc = "..."]`) and join them.
fn extract_doc_comment(attrs: &[syn::Attribute]) -> Option<String> {
    let mut lines = Vec::new();
    for attr in attrs.iter().filter(|a| a.path().is_ident("doc")) {
        if let syn::Meta::NameValue(meta) = &attr.meta {
            if let syn::Expr::Lit(syn::ExprLit {
                lit: syn::Lit::Str(s),
                ..
            }) = &meta.value
            {
                let val = s.value();
                let trimmed = val.strip_prefix(' ').unwrap_or(&val);
                lines.push(trimmed.trim_end().to_string());
            }
        }
    }
    if lines.is_empty() {
        None
    } else {
        Some(lines.join("\n").trim().to_string())
    }
}

/// Check container-level `#[serde(rename_all = "...")]`.
fn container_serde_rename_all(attrs: &[syn::Attribute]) -> syn::Result<Option<String>> {
    let mut rename_all = None;
    for attr in attrs.iter().filter(|a| a.path().is_ident("serde")) {
        attr.parse_nested_meta(|meta| {
            if meta.path.is_ident("rename_all") {
                let lit: syn::LitStr = meta.value()?.parse()?;
                rename_all = Some(lit.value());
            } else if meta.input.peek(syn::Token![=]) {
                let _: syn::Expr = meta.value()?.parse()?;
            }
            Ok(())
        })?;
    }
    Ok(rename_all)
}

/// Apply serde `rename_all` rules to variant identifiers.
fn apply_rename_all(name: &str, rule: &str) -> String {
    match rule {
        "lowercase" => name.to_lowercase(),
        "UPPERCASE" => name.to_uppercase(),
        "snake_case" => to_snake_case(name),
        "SCREAMING_SNAKE_CASE" => to_snake_case(name).to_uppercase(),
        "kebab-case" => to_snake_case(name).replace('_', "-"),
        "SCREAMING-KEBAB-CASE" => to_snake_case(name).to_uppercase().replace('_', "-"),
        "camelCase" => to_camel_case(name),
        "PascalCase" => name.to_string(),
        _ => name.to_string(),
    }
}

fn to_snake_case(s: &str) -> String {
    let mut out = String::new();
    for (i, ch) in s.chars().enumerate() {
        if ch.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.extend(ch.to_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

fn to_camel_case(s: &str) -> String {
    let snake = to_snake_case(s);
    let mut out = String::new();
    let mut capitalize_next = false;
    for ch in snake.chars() {
        if ch == '_' {
            capitalize_next = true;
        } else if capitalize_next {
            out.extend(ch.to_uppercase());
            capitalize_next = false;
        } else {
            out.push(ch);
        }
    }
    out
}

/// Map a Rust field type to its property schema and optional status.
fn json_type(ty: &Type, choices: Option<&[String]>) -> (serde_json::Value, bool) {
    if let Some(inner) = strip_single_generic_arg(ty, "Option") {
        let (schema, _) = json_type(inner, choices);
        return (schema, true);
    }
    if let Some(inner) = strip_single_generic_arg(ty, "Vec") {
        if let Some(choices) = choices {
            let choice_vals: Vec<serde_json::Value> =
                choices.iter().cloned().map(Into::into).collect();
            return (
                serde_json::json!({
                    "type": "array",
                    "items": {
                        "type": "string",
                        "enum": choice_vals
                    }
                }),
                false,
            );
        }
        return match scalar_json_type(inner) {
            Some(item) => (
                serde_json::json!({"type": "array", "items": {"type": item}}),
                false,
            ),
            None => (serde_json::json!({"type": "object"}), false),
        };
    }

    if let Some(choices) = choices {
        let choice_vals: Vec<serde_json::Value> = choices.iter().cloned().map(Into::into).collect();
        return (
            serde_json::json!({
                "type": "string",
                "enum": choice_vals
            }),
            false,
        );
    }

    let scalar = scalar_json_type(ty).unwrap_or("object");
    (serde_json::json!({"type": scalar}), false)
}

/// The JSON-Schema scalar type for a Rust primitive, or `None` for anything else.
fn scalar_json_type(ty: &Type) -> Option<&'static str> {
    if let Type::Reference(r) = ty {
        return match &*r.elem {
            Type::Path(p) if p.path.is_ident("str") => Some("string"),
            _ => None,
        };
    }
    match type_to_string(ty).as_str() {
        "String" => Some("string"),
        "bool" => Some("boolean"),
        "i8" | "i16" | "i32" | "i64" | "isize" | "u8" | "u16" | "u32" | "u64" | "usize" => {
            Some("integer")
        }
        "f32" | "f64" => Some("number"),
        _ => None,
    }
}

fn type_to_string(ty: &Type) -> String {
    quote::quote!(#ty).to_string().replace(' ', "")
}

/// If `ty` is `<ident><T>` (e.g. `Option<T>` / `Vec<T>`), return the inner `T`.
fn strip_single_generic_arg<'a>(ty: &'a Type, ident: &str) -> Option<&'a Type> {
    let path = match ty {
        Type::Path(p) => &p.path,
        _ => return None,
    };
    let last = path.segments.last()?;
    if last.ident != ident {
        return None;
    }
    let args = match &last.arguments {
        syn::PathArguments::AngleBracketed(a) => &a.args,
        _ => return None,
    };
    if let Some(syn::GenericArgument::Type(inner)) = args.first() {
        Some(inner)
    } else {
        None
    }
}

